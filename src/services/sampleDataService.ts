/**
 * Downloads a pre-formatted Excel template matching the 17-column structure
 */
export function downloadSampleExcelTemplate(): void {
  const exportRows = SAMPLE_OCTOBER_DUES.map(row => ({
    'InvNo': row.invoice_no,
    'Inv Year': row.inv_year,
    'Inv Month': row.inv_month,
    'Date': row.date,
    'Clientid': row.client_id || '',
    'Client': row.client_name,
    'User': row.user_name,
    'Invoice type': row.invoice_type,
    'Email': row.email || '',
    'Mobile': row.mobile || '',
    'Home': row.home || '',
    'Invoice Amount': row.amount,
    'Return': row.return_amount || 0,
    'Sold': row.sold_amount || row.amount,
    'Balance (As of now)': row.balance,
    'Mode of payment': row.mode_of_payment,
    'Clinic': row.clinic_name,
  }));

  const worksheet = XLSX.utils.json_to_sheet(exportRows);
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, 'October Due 17-Col');
  XLSX.writeFile(workbook, 'MaxPetZ_October_Due_17_Columns_Template.xlsx');
}
